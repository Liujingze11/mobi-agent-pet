const dictionaries: Record<ManagerLocale, Record<TranslationKey, string>> = { en, zh };

export function normalizeManagerLocale(language: string): ManagerLocale {
  return language === "zh" ? "zh" : "en";
}

export function createTranslator(locale: ManagerLocale) {
  return (key: TranslationKey, values: Record<string, string | number> = {}) => {
    const template = dictionaries[locale][key] || en[key];
    return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
  };
}

type I18nValue = {
  locale: ManagerLocale;
  t: ReturnType<typeof createTranslator>;
};

const I18nContext = createContext<I18nValue>({ locale: "en", t: createTranslator("en") });

export function I18nProvider({ children, locale }: { children: ReactNode; locale: ManagerLocale }) {
  return <I18nContext.Provider value={{ locale, t: createTranslator(locale) }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

